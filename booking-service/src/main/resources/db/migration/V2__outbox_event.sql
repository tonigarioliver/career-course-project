-- Fase 4 — Transactional Outbox. Written in the same transaction as the reservation, so
-- "reservation exists" and "event will be published" commit or roll back together; OutboxRelay
-- ships unpublished rows to Kafka afterwards.
CREATE TABLE outbox_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic VARCHAR(255) NOT NULL,
    message_key VARCHAR(255) NOT NULL,
    payload TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    published_at TIMESTAMPTZ
);

-- Partial: the relay only ever scans the unpublished tail, which stays tiny.
CREATE INDEX idx_outbox_event_unpublished ON outbox_event (id) WHERE published_at IS NULL;
