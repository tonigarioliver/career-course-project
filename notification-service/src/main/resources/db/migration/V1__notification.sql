-- Inbox of reservation events to notify about. event_id UNIQUE = idempotency (the producer's
-- outbox is at-least-once). next_attempt_at doubles as retry delay and as the worker's lease.
CREATE TABLE notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(255) NOT NULL UNIQUE,
    reservation_id BIGINT NOT NULL,
    owner_subject VARCHAR(255),
    status VARCHAR(20) NOT NULL,
    attempts INT NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL,
    last_error TEXT,
    recipient VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL,
    sent_at TIMESTAMPTZ
);

-- Partial: the worker only scans pending rows.
CREATE INDEX idx_notification_due ON notification (next_attempt_at) WHERE status = 'PENDING';
