-- Audit trail of every event consumed from Kafka. event_id UNIQUE is the idempotency key: the
-- producer's outbox is at-least-once, so the same event can arrive twice and the second insert
-- must be a no-op (see AuditEventRepository.insertIfAbsent).
CREATE TABLE audit_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(255) NOT NULL UNIQUE,
    event_type VARCHAR(100) NOT NULL,
    resource_id BIGINT NOT NULL,
    payload TEXT NOT NULL,
    received_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_audit_event_resource ON audit_event (resource_id, id DESC);
